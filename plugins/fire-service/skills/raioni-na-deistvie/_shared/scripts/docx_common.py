#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
docx_common.py — the typography rules and the final check shared by every script that builds a document
(_shared/conventions.md, т. 2): „№ 4“, the dash „–“ between words (a lone „-“ between spaces and „—“ become „–“;
the hyphen inside words and numbers stays; the letterhead keeps its own), no bold, one letterhead.

    from docx_common import typo, typo_all, check_document, report

    typo("ул. Иван Вазов №4 - Плевен")        →  "ул. Иван Вазов № 4 – Плевен"
    typo("№ 3–7, 2-3 °C, ПЛАН-КОНСПЕКТ")      →  "№ 3-7, 2-3 °C, ПЛАН-КОНСПЕКТ"
    typo_all(doc)                              applies typo() to the body, the headers and the footers
    check_document("out.docx")                 →  [] or a list of what breaks the rules
    report("out.docx")                         sets the file's author (stamp) and prints the problems to stderr
                                               (the builders call it after saving)
    stamp("out.xlsx")                          the file's metadata: Authors/Last modified by = the user of the
                                               personal key (e.g. „Пламен Марков“), no „python-docx“/„openpyxl“

    python3 docx_common.py out.docx            # the same check from the command line; exit code 1 on a problem
"""
import os
import re
import sys
import zipfile

NO_RE = re.compile(r"№\s*(?=\S)")          # „№4“ → „№ 4“
DASH_RE = re.compile(r"(?<=\s)-(?=\s)|—")  # a lone „-“ between spaces and „—“ → „–“ (since 09.11.2026)
RANGE_RE = re.compile(r"(?<=\d)[–—](?=\d)")   # „3–7“ → „3-7“ (ranges keep the hyphen)
LETTERHEAD_MARK = "ПОЖАРНА БЕЗОПАСНОСТ И ЗАЩИТА НА НАСЕЛЕНИЕТО"   # the letterhead keeps its dash
SPACED_TITLE_RE = re.compile(r"^\s*(\S )+– (\S ?)+$")   # „П Л А Н – К О Н С П Е К Т“ keeps its dash „–“ (08.11.2026)


def keeps_dash(text):
    """The letterhead lines and a spaced-letter title are left as they are."""
    return LETTERHEAD_MARK in text.upper() or bool(SPACED_TITLE_RE.match(text))
BOLD_RE = re.compile(r"<w:b(Cs)?[ /]|<b/>|<b val=\"(1|true)\"")
TAG_RE = re.compile(r"<[^>]+>")
LETTERHEAD = ("МИНИСТЕРСТВО НА ВЪТРЕШНИТЕ РАБОТИ",
              "ГЛАВНА ДИРЕКЦИЯ „ПОЖАРНА БЕЗОПАСНОСТ И ЗАЩИТА НА НАСЕЛЕНИЕТО”")
THIRD_LINE = re.compile(r"(РЕГИОНАЛНА ДИРЕКЦИЯ|РАЙОННА СЛУЖБА) „ПОЖАРНА БЕЗОПАСНОСТ И ЗАЩИТА НА НАСЕЛЕНИЕТО” – \S")


def typo(text, quotes=False):
    """„№ 4“; the dash between words is „–“: a lone „-“ between spaces and „—“ become „–“ (the user's rule
    since 09.11.2026); hyphens inside words and numbers („2-3 °C“, „1234р-56789“) stay „-“. The letterhead
    lines and a spaced-letter title are left as they are.
    With quotes=True the closing quote „”“ becomes „“ “."""
    text = NO_RE.sub("№ ", str(text))
    if quotes:
        text = text.replace("”", "“")
    if keeps_dash(text):
        return text
    return DASH_RE.sub("–", RANGE_RE.sub("-", text))


def typo_all(doc, tag=None, quotes=False):
    """typo() over the whole python-docx document – body, text boxes, headers and footers."""
    if tag is None:
        from docx.oxml.ns import qn
        tag = qn("w:t")
    parts = [doc.element.body]
    for sec in doc.sections:
        for hf in (sec.header, sec.first_page_header, sec.even_page_header,
                   sec.footer, sec.first_page_footer, sec.even_page_footer):
            parts.append(hf._element)
    for part in parts:
        for t in part.iter(tag):
            if t.text:
                t.text = typo(t.text, quotes)


def _texts(path):
    """(part name, raw xml, plain text) for the parts of a .docx/.xlsx that carry text."""
    out = []
    with zipfile.ZipFile(path) as z:
        for n in z.namelist():
            if re.match(r"word/(document|header\d*|footer\d*)\.xml$|xl/(sharedStrings|worksheets/sheet\d+)\.xml$", n):
                xml = z.read(n).decode("utf-8", "ignore")
                paras = re.split(r"</w:p>|</si>|</c>", xml)
                out.append((n, xml, [TAG_RE.sub("", p) for p in paras]))
    return out


# ---- the file's metadata (Authors, Last modified by, Comments) ------------------------------------------------
# python-docx writes „python-docx“ / „generated by python-docx“ and openpyxl „openpyxl“ into docProps/core.xml.
# The owner's rule (16.11.2026): the author of every generated file is the user of the personal key.
LIBRARY_MARK_RE = re.compile(r"python-docx|openpyxl", re.I)
_AUTHOR = None


def author_name():
    """The name of the user of the personal key („Пламен Марков“): FIRE_SERVICE_AVTOR (set by fire-render for the
    colleague who asked), else `ime` from the personal skill, else the owner of the key (n8n whoami). Empty when
    unknown – never the name of a library."""
    global _AUTHOR
    if _AUTHOR is not None:
        return _AUTHOR
    name = ""
    if "FIRE_SERVICE_AVTOR" in os.environ:
        name = os.environ["FIRE_SERVICE_AVTOR"]
    else:
        try:
            sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
            import api_config
            name = api_config.profile().get("ime") or ""
            if not name and api_config.has_key():
                who = api_config.post("staff_url", {"action": "whoami"}, timeout=15) or {}
                name = who.get("client") or ""
        except BaseException:  # noqa: BLE001  (no key, no network – the file is still written, just without a name)
            name = ""
    _AUTHOR = str(name).strip()
    return _AUTHOR


CORE_NS = {"dc": "http://purl.org/dc/elements/1.1/",
           "cp": "http://schemas.openxmlformats.org/package/2006/metadata/core-properties"}


def _set_core(xml, tag, value):
    """Set <tag>value</tag> in docProps/core.xml, keeping the element's own attributes (openpyxl declares the
    namespace on the element itself); an empty value removes the element; a missing one is added with its
    namespace declared."""
    esc = value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    pat = re.compile(rf"<{tag}(\s[^>]*?)?\s*/>|<{tag}(\s[^>]*)?>.*?</{tag}>", re.S)
    m = pat.search(xml)
    if m:
        attrs = m.group(1) or m.group(2) or ""
        new = f"<{tag}{attrs}>{esc}</{tag}>" if esc else ""
        return xml[:m.start()] + new + xml[m.end():]
    if not esc:
        return xml
    prefix = tag.split(":")[0]
    decl = "" if f"xmlns:{prefix}=" in xml.split(">", 2)[1] + ">" else f' xmlns:{prefix}="{CORE_NS[prefix]}"'
    return xml.replace("</cp:coreProperties>", f"<{tag}{decl}>{esc}</{tag}></cp:coreProperties>")


def stamp(path, author=None):
    """Write the user's name as Authors and Last modified by of a finished .docx/.xlsx and clear Comments
    („generated by python-docx“). Never stops the builder."""
    try:
        name = author_name() if author is None else str(author).strip()
        with zipfile.ZipFile(path) as z:
            items = [(i, z.read(i.filename)) for i in z.infolist()]
        core = next((d for i, d in items if i.filename == "docProps/core.xml"), None)
        if core is None:
            return
        xml = core.decode("utf-8")
        new = _set_core(_set_core(xml, "dc:creator", name), "cp:lastModifiedBy", name)
        new = _set_core(new, "dc:description", "")
        if new == xml:
            return
        tmp = path + ".tmp"
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
            for i, d in items:
                z.writestr(i, new.encode("utf-8") if i.filename == "docProps/core.xml" else d)
        os.replace(tmp, path)
    except Exception as e:  # noqa: BLE001
        print(f"DOC_CHECK: авторът на файла не можа да се запише ({type(e).__name__})", file=sys.stderr)


def _core_problems(path):
    with zipfile.ZipFile(path) as z:
        if "docProps/core.xml" not in z.namelist():
            return []
        xml = z.read("docProps/core.xml").decode("utf-8", "ignore")
    return ["в свойствата на файла (Authors/Comments) е името на библиотеката – виж stamp()"] \
        if LIBRARY_MARK_RE.search(xml) else []


def check_document(path, letterhead=True):
    """What in a finished document breaks the common rules. An empty list means it is fine."""
    problems = []
    body = ""
    for name, xml, paras in _texts(path):
        if BOLD_RE.search(xml):
            problems.append(f"получер шрифт в {name}")
        for p in paras:
            m = DASH_RE.search(p)
            if m and not keeps_dash(p):
                problems.append(f"тире „{m.group(0)}“ вместо „–“: …{p[max(0, m.start() - 20):m.start() + 20]}…")
            if re.search(r"№\S", p):
                problems.append(f"„№“ без интервал: …{p[max(0, p.find('№') - 15):p.find('№') + 15]}…")
            m = re.search(r"\{\{\w+\}\}", p)
            if m:
                problems.append(f"непопълнено поле: {m.group(0)}")
        if name == "word/document.xml":
            body = "".join(paras)
    problems += _core_problems(path)
    if letterhead and path.lower().endswith(".docx"):
        for line in LETTERHEAD:
            if line not in body:
                problems.append(f"в шапката липсва ред „{line}“")
        if not THIRD_LINE.search(body):
            problems.append("третият ред на шапката не е изписан изцяло („РЕГИОНАЛНА ДИРЕКЦИЯ …“ / „РАЙОННА СЛУЖБА …“)")
    return sorted(set(problems))


def report(path, letterhead=True):
    """Stamp the user's name into the file's metadata (stamp), then print the problems of the finished
    document to stderr; returns them. Never stops the builder."""
    stamp(path)
    try:
        problems = check_document(path, letterhead)
    except Exception as e:  # noqa: BLE001  (the check must never break a finished document)
        print(f"DOC_CHECK: проверката не можа да се изпълни ({type(e).__name__})", file=sys.stderr)
        return []
    for p in problems:
        print(f"DOC_CHECK: {p}", file=sys.stderr)
    return problems


if __name__ == "__main__":
    bad = False
    for f in sys.argv[1:]:
        found = check_document(f, letterhead="--no-letterhead" not in sys.argv)
        bad = bad or bool(found)
        print(f"{'✗' if found else '✓'} {f}")
        for line in found:
            print("   ", line)
    sys.exit(1 if bad else 0)
